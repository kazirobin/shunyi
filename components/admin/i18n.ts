export function formatYmd(locale: AdminLocale, ymd: string, opts: Intl.DateTimeFormatOptions) {
  const d = new Date(`${ymd}T00:00:00`);
  return Number.isNaN(d.getTime()) ? ymd : d.toLocaleDateString(INTL[locale], opts);
}

